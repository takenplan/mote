package dev.mote.collector

import org.json.JSONObject
import org.junit.Assert.*
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import java.io.ByteArrayInputStream
import java.util.UUID

class FileSyncProgressTest {
    @get:Rule val temporary = TemporaryFolder()
    private val cipher = LocalContentCipher()
    private fun source() = LocalSource(id = "generated-folder", name = "Generated folder", kind = "local-files", tree = true, uri = "content://generated/tree", extensions = "txt", retention = "archive")
    private fun item(id: String = "one") = JSONObject().put("externalId", "content://generated/$id.txt").put("uri", "content://generated/$id.txt").put("title", "$id.txt")
        .put("kind", "file").put("layer", "original").put("mimeType", "text/plain").put("text", "").put("observedAt", "2026-10-13T00:00:00Z")
    private fun ack(row: JSONObject): JSONObject {
        val manifest = row.getJSONObject("pending").getJSONObject("manifest"); val candidate = manifest.getJSONObject("item"); val id = UUID.randomUUID().toString()
        return JSONObject().put("id", id).put("sourceId", manifest.getString("sourceId")).put("externalId", candidate.getString("externalId")).put("revision", candidate.getString("revision"))
            .put("duplicate", false).put("sha256", manifest.getString("sha256")).put("sizeBytes", manifest.getLong("sizeBytes"))
            .put("receipt", JSONObject().put("version", 2).put("id", id).put("kind", "file-revision").put("state", "received").put("duplicate", false)
                .put("sourceId", manifest.getString("sourceId")).put("externalId", candidate.getString("externalId")).put("revision", candidate.getString("revision")))
    }
    @Test fun initialFolderDistinguishesStabilityFromQueueAndDoesNotNeedAnotherScan() {
        val queue = FileArchiveQueue(temporary.newFolder(), cipher); val source = source()
        val generation = queue.configure(source).getString("generation")
        queue.observe(source, item(), generation, 1000)
        assertEquals(1, queue.progress(source, 60999).count(FileSyncPhase.STABILITY))
        assertFalse(queue.progress(source, 60999).scanComplete)
        assertEquals(1, queue.progress(source, 61000).count(FileSyncPhase.QUEUED))
        assertTrue(LocalContentPresentation.fileStatus(queue.row(source.id, item().getString("externalId")), 60999).contains("1 秒"))
        assertTrue(LocalContentPresentation.fileStatus(queue.row(source.id, item().getString("externalId")), 61000).contains("排队"))
        queue.finish(source, generation) { false }
        assertTrue(queue.progress(source, 61000).scanComplete)
        queue.observe(source, item().put("modifiedAt", "2026-10-13T01:00:00Z"), queue.state(source.id).getString("generation"), 62000)
        assertEquals(1, queue.progress(source, 62001).count(FileSyncPhase.STABILITY))
    }
    @Test fun savedBytesAreQueuedUntilARealAttemptAndFailureSurvivesRestartUntilAck() {
        val directory = temporary.newFolder(); val source = source(); val queue = FileArchiveQueue(directory, cipher)
        queue.observe(source, item(), queue.configure(source).getString("generation"), 0)
        assertEquals(1, queue.progress(source, 61000).count(FileSyncPhase.QUEUED)) // initializes the incremental inventory
        val row = queue.prepare(source, { ByteArrayInputStream("Generated bytes".toByteArray()) }, { true }, 61000)!!
        assertEquals(1, queue.progress(source, 61000).count(FileSyncPhase.QUEUED))
        val owner = Any(); val key = queue.transferKey(source.id)
        try {
            FileSyncTransfers.set(key, owner, FileSyncTransfer(FileSyncEntry.from(row).key, FileSyncPhase.UPLOADING))
            assertEquals(1, queue.progress(source, 61000).count(FileSyncPhase.UPLOADING))
            assertTrue(LocalContentPresentation.fileStatus(queue.presentationRow(source, row)).contains("正在上传"))
            queue.recordFailure(source, row, "upload", 503)
        } finally { FileSyncTransfers.clear(key, owner) }
        val restarted = FileArchiveQueue(directory, cipher)
        assertEquals(1, restarted.progress(source, 61000).count(FileSyncPhase.RETRY))
        assertTrue(LocalContentPresentation.fileStatus(restarted.row(source.id, item().getString("externalId"))).contains("HTTP 503"))
        assertTrue(restarted.pendingPage(source.id, 0).getJSONArray("items").getJSONObject(0).getString("status").contains("等待重试"))
        restarted.acknowledge(source.id, restarted.next(source.id)!!, ack(row))
        assertEquals(1, restarted.progress(source, 61000).received)
        assertEquals(0, restarted.progress(source, 61000).count(FileSyncPhase.RETRY))
        val changed = item().put("modifiedAt", "2026-10-13T01:00:00Z")
        restarted.observe(source, changed, restarted.state(source.id).getString("generation"), 62000)
        assertEquals(0, restarted.progress(source, 62001).received)
        assertEquals(1, restarted.progress(source, 62001).count(FileSyncPhase.STABILITY))
        restarted.recordFailure(source, row, "upload", 503)
        assertFalse("A late failure must not label the new version", restarted.row(source.id, changed.getString("externalId")).has("syncFailure"))
    }
    @Test fun baselineFilesDoNotMakeNewOnlyProgressLookIncompleteAndPolicyEditsUpdateCounts() {
        val queue = FileArchiveQueue(temporary.newFolder(), cipher); val source = source().copy(initialSync = "new_only")
        val generation = queue.configure(source).getString("generation")
        queue.observe(source, item(), generation, 0); queue.finish(source, generation) { false }
        assertEquals(0, queue.progress(source, 61000).total)
        assertEquals(1, queue.progress(source, 61000).count(FileSyncPhase.BASELINE))
        assertTrue(queue.progress(source, 61000).summary().contains("不发送：1"))
        val all = source.copy(initialSync = "all"); queue.configure(all)
        assertEquals(1, queue.progress(all, 61000).total)
        assertEquals(1, queue.progress(all, 61000).count(FileSyncPhase.QUEUED))
        queue.configure(all.copy(excluded = "*.txt"))
        assertEquals(0, queue.progress(all, 61000).total)
        queue.remove(source.id)
        assertEquals(0, queue.progress(source, 61000).total)
    }
    @Test fun copyFailureAndReferenceAndImmediateImportKeepTheirDifferentStateTransitions() {
        val queue = FileArchiveQueue(temporary.newFolder(), cipher); val source = source()
        queue.observe(source, item(), queue.configure(source).getString("generation"), 0)
        assertThrows(IllegalStateException::class.java) { queue.prepare(source, { error("Generated read failure") }, { true }, 61000) }
        assertEquals(1, queue.progress(source, 61001).count(FileSyncPhase.RETRY))
        assertFalse(queue.transportReady(source.id, 61001))
        queue.prepare(source, { ByteArrayInputStream(byteArrayOf(1)) }, { true }, 121000)!!
        assertEquals(1, queue.progress(source, 121001).count(FileSyncPhase.QUEUED))
        val reference = JSONObject().put("candidate", item().put("layer", "reference")).put("stableSince", 1000)
        assertEquals(FileSyncPhase.QUEUED, FileSyncEntry.from(reference).phase(1000))
        val immediate = JSONObject().put("candidate", item()).put("stableSince", 1000)
        assertEquals(FileSyncPhase.QUEUED, FileSyncEntry.from(immediate, immediate = true).phase(1000))
        queue.recordFailure(source, queue.next(source.id)!!, "upload", 410, blocked = true)
        assertEquals(1, queue.progress(source, 121001).count(FileSyncPhase.BLOCKED))
        assertEquals(0, queue.progress(source, 121001).count(FileSyncPhase.RETRY))
    }
    @Test fun recentRowsObserveWritesAndKeepProgressIndependentOfTheVisibleSubset() {
        val queue = FileArchiveQueue(temporary.newFolder(), cipher); val source = source()
        val generation = queue.configure(source).getString("generation")
        queue.observe(source, item("first"), generation, 0)
        queue.observe(source, item("second").put("observedAt", "2026-10-13T00:01:00Z"), generation, 0)
        assertEquals("second.txt", queue.recentRows(source, 1).single().getJSONObject("candidate").getString("title"))
        assertEquals(2, queue.progress(source, 61000).total)
        queue.observe(source, item("first").put("observedAt", "2026-10-13T00:02:00Z"), generation, 62000)
        assertEquals("first.txt", queue.recentRows(source, 1).single().getJSONObject("candidate").getString("title"))
        assertEquals("STABILITY", FileSyncEntry.from(queue.recentRows(source, 1).single()).phase(1000).name)
        assertEquals(2, queue.progress(source, 62000).count(FileSyncPhase.QUEUED))
    }
    @Test fun anOldAttemptFinishingCannotClearItsSuccessorsLiveStatus() {
        val first = Any(); val successor = Any(); val key = "generated-transfer-${UUID.randomUUID()}"
        FileSyncTransfers.set(key, first, FileSyncTransfer("one", FileSyncPhase.PREPARING))
        FileSyncTransfers.set(key, successor, FileSyncTransfer("two", FileSyncPhase.UPLOADING))
        FileSyncTransfers.clear(key, first)
        assertEquals("two", FileSyncTransfers.get(key)?.key)
        FileSyncTransfers.clear(key, successor)
        assertNull(FileSyncTransfers.get(key))
    }
}
