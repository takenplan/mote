import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,readFile,rm,stat} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {storageOwnerPlan,parseStorageOwner} from '../storage-owner-entry.mjs';
import {migrateStorageOwner} from '../profile-lib.mjs';
test('nonempty legacy-owned volume rejects before changing any empty volume root',async t=>{
 const root=await mkdtemp(join(tmpdir(),'mote-storage-owner-'));t.after(()=>rm(root,{recursive:true,force:true}));const empty=join(root,'empty'),legacy=join(root,'legacy');await mkdir(empty);await mkdir(legacy);await writeFile(join(legacy,'generated'),'generated bytes');
 const before=await stat(empty),otherUser=`${before.uid===1000?1001:1000}:${before.gid}`;
 await assert.rejects(storageOwnerPlan(otherUser,[empty,legacy]),/migrate-storage-owner/);
 assert.equal((await stat(empty)).uid,before.uid);assert.equal(await readFile(join(legacy,'generated'),'utf8'),'generated bytes');
 assert.deepEqual(await storageOwnerPlan(`${before.uid}:${before.gid}`,[empty,legacy]),{uid:before.uid,gid:before.gid,initialize:[]});
 assert.deepEqual((await storageOwnerPlan(otherUser,[empty])).initialize,[empty]);
 for(const value of ['root:root','1','1:2:3','-1:2','4294967295:0'])assert.throws(()=>parseStorageOwner(value));
});
test('explicit migration checks only the selected known volumes and refuses running users',async()=>{
 const p={profile:'test',meta:{runtime:'docker',volume:'generated-data',modelsVolume:'generated-models'},modelDirectory:'/generated-model-resources'},calls=[];
 const dependencies={configurationUser:async()=> '501:20',execute:async(_command,args)=>{calls.push(args);return '';},compose:async(_p,args)=>{calls.push(args);}};
 assert.deepEqual(await migrateStorageOwner(p,dependencies),{migrated:true,profile:'test',owner:'501:20',started:false});
 assert.deepEqual(calls.at(-1),['run','--rm','--no-deps','storage-init','node','scripts/storage-owner-entry.mjs','--migrate','501:20','/data','/generated-model-resources','/worker-facts']);
 assert.deepEqual(calls.filter(args=>args[0]==='ps').map(args=>args[2]),['volume=generated-data','volume=generated-models']);
 let mutated=false;await assert.rejects(migrateStorageOwner(p,{...dependencies,execute:async(_command,args)=>args[0]==='ps'?'generated-running-container':'',compose:async()=>{mutated=true;}}),/Stop every container/);assert.equal(mutated,false);
});
