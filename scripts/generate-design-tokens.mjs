import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const root=new URL('../',import.meta.url);
const tokens=JSON.parse(readFileSync(new URL('packages/shared/design-tokens.json',root),'utf8'));
const layout={id:'mote.workspace',version:'1',primary:['library','ask','sources','activity'],initial:'library',navigation:'adaptive',detail:'split'};
const theme={id:'mote.linear',version:'1',tokens};
const name=key=>key.replace(/-([a-z])/g,(_,c)=>c.toUpperCase());
const colors=Object.entries(tokens).filter(([,value])=>/^#[\da-f]{6}$/i.test(value));
const dimensions=Object.entries(tokens).filter(([,value])=>/^\d+px$/.test(value));
const numbers=Object.entries(tokens).filter(([,value])=>/^\d+(?:\.\d+)?$/.test(value));
const css='/* Generated by scripts/generate-design-tokens.mjs. */\n:root {\n'+Object.entries(tokens).map(([key,value])=>`  --mote-${key}: ${value};`).join('\n')+'\n}\n';
const outputs=new Map(['web','desktop'].map(app=>[`apps/${app}/src/design-tokens.css`,css]));
outputs.set('packages/shared/src/ui-theme.generated.ts','// Generated by scripts/generate-design-tokens.mjs.\nexport const linearThemeTokens = '+JSON.stringify(tokens,null,2)+' as const;\n');
outputs.set('apps/android/app/src/main/java/dev/mote/collector/DesignTokens.kt','// Generated by scripts/generate-design-tokens.mjs.\npackage dev.mote.collector\n\nobject DesignTokens {\n'+colors.map(([key,value])=>`    val ${name(key)} = android.graphics.Color.parseColor("${value}")`).join('\n')+'\n'+dimensions.map(([key,value])=>`    const val ${name(key)} = ${Number.parseInt(value,10)}`).join('\n')+'\n'+numbers.map(([key,value])=>`    const val ${name(key)} = ${value}`).join('\n')+'\n}\n');
outputs.set('apps/android/app/src/main/res/values/design-tokens.xml','<!-- Generated by scripts/generate-design-tokens.mjs. -->\n<resources>\n'+colors.map(([key,value])=>`    <color name="mote_${key.replaceAll('-', '_')}">${value}</color>`).join('\n')+'\n</resources>\n');
outputs.set('apps/android/app/src/main/assets/design-tokens.json',JSON.stringify(tokens,null,2)+'\n');
outputs.set('apps/android/app/src/main/assets/ui-presentation.json',JSON.stringify({schemaVersion:1,theme,layout},null,2)+'\n');
const check=process.argv.includes('--check');
for(const [path,value] of outputs){
  const url=new URL(path,root);
  if(check){if(readFileSync(url,'utf8')!==value)throw Error('Stale generated UI resource: '+path);}
  else writeFileSync(fileURLToPath(url),value);
}
